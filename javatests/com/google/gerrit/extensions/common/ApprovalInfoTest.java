package com.google.gerrit.extensions.common;

import static com.google.common.truth.Truth.assertThat;

import java.time.Instant;
import org.junit.Test;
import org.junit.runner.RunWith;
import org.junit.runners.JUnit4;

@RunWith(JUnit4.class)
public class ApprovalInfoTest {
  @Test
  public void isAi_setFromAiTag() {
    ApprovalInfo aiCoverageApproval = new ApprovalInfo(1, 1, null, "ai-coverage", Instant.EPOCH);
    assertThat(aiCoverageApproval.isAi).isTrue();

    ApprovalInfo autogeneratedAiApproval =
        new ApprovalInfo(1, 1, null, "autogenerated:ai-review", Instant.EPOCH);
    assertThat(autogeneratedAiApproval.isAi).isTrue();
  }

  @Test
  public void isAi_nullForNonAiOrNullTag() {
    ApprovalInfo regularTagApproval = new ApprovalInfo(1, 1, null, "coverage", Instant.EPOCH);
    assertThat(regularTagApproval.isAi).isNull();

    ApprovalInfo nullTagApproval = new ApprovalInfo(1, 1, null, null, Instant.EPOCH);
    assertThat(nullTagApproval.isAi).isNull();
  }
}
